def build_owner_reels(owner, campaigns, month):
    if owner == "Алексей":
        main, short, prefix = KARP_MAIN, KARP_SHORT, "karp"
    elif owner == "Вероника":
        main, short, prefix = VERONIKA_MAIN, VERONIKA_SHORT, "veronika"
    else:
        raise ValueError("No reviewed owner scripts for this owner")
    result = []
    start = datetime.fromisoformat(month + "-01").replace(tzinfo=WARSAW)
    for lane, scripts, hour, minute in (("main", main, 19, 0), ("short", short, 12, 30)):
        if len(scripts) != 30:
            raise ValueError(f"{owner}: expected 30 {lane} scripts, found {len(scripts)}")
        for index, concept in enumerate(scripts):
            campaign_index = concept["campaign"]
            campaign = campaigns[campaign_index - 1]["article"] if campaign_index else "Коммерческая недвижимость под задачу бизнеса"
            publish_at = (start + timedelta(days=index)).replace(hour=hour, minute=minute)
            parts = [concept[key] for key in ("hook", "development", "payoff", "cta")]
            word_counts = [len(re.findall(r"[\w]+", part)) for part in parts]
            # Leave room for real speech, showing an object and a reaction.
            beat_lengths = [max(2, math.ceil(count / 2.1)) for count in word_counts]
            beat_lengths[1] += 2 if lane == "main" else 1
            beat_lengths[2] += max(0, (30 if lane == "main" else 16) - sum(beat_lengths))
            duration = sum(beat_lengths)
            cursor = 0
            beats = []
            for label, part, length in zip(("Начало", "Развитие", "Развязка", "Призыв"), parts, beat_lengths):
                beats.append(f"{cursor:02d}–{cursor + length:02d} с · {label}: «{part}»")
                cursor += length
            title = concept["title"]
            brief = f"{'Основной ролик' if lane == 'main' else 'Короткий ролик'} · {duration} с. " + concept["shots"][0]
            details = {
                "planMonth": month, "publishAt": publish_at.isoformat(timespec="minutes"),
                "productionDueAt": (publish_at - timedelta(days=2)).isoformat(timespec="minutes"),
                "recordingDueAt": (publish_at - timedelta(days=3)).isoformat(timespec="minutes"),
                "brief": brief, "contentSummary": concept["retention"], "campaign": campaign,
                "reelCategory": concept["category"], "hook": concept["hook"],
                "talkingPoints": beats, "shotList": concept["shots"],
                "cta": concept["cta"], "retentionReason": concept["retention"],
                "durationSeconds": duration, "spokenText": " ".join(parts),
                "scriptRevision": REVISION, "reelScriptId": f"{prefix}-{lane}-{index + 1:02d}",
                "reelLane": lane, "shootingPair": f"{prefix}-day-{index + 1:02d}",
                "recordingNote": "Основной и короткий ролики этого дня снимайте вместе. Отдельный первый кадр и отдельная реплика для каждого: второй ролик не является обрезком первого.",
                "deliverable": f"Один вертикальный ролик 9:16, ориентир {duration} с. Говорить своими интонациями; реплики можно упростить без потери смысла. Чистый голос и субтитры. Записать и опубликовать лично в Instagram Reels, TikTok и YouTube Shorts. Учебные сцены обозначать, реальные наблюдения не выдумывать.",
            }
            if concept["keyword"]:
                keyword = concept["keyword"]
                material_title, content = MATERIALS[keyword]
                details["leadMagnet"] = {
                    "keyword": keyword, "title": material_title, "content": content,
                    "replyText": "Вот обещанный материал: " + material_title + ".\n\n" + "\n\n".join(content),
                    "delivery": "После запроса ответьте человеку вручную. В Instagram можно отправить материал в личном сообщении. Для TikTok и YouTube используйте ответ на комментарий, при необходимости несколькими сообщениями. Автоматическая выдача не подключена; не обещайте её в речи.",
                }
            result.append({
                "week": min(5, index // 7 + 1), "channel": "Instagram Reels + TikTok + YouTube Shorts",
                "format": f"Живой ролик · {duration} с", "title": title, "objective": brief,
                "funnel_stage": "Диалог и запрос материала" if concept["keyword"] else "Охват, узнавание и доверие",
                "cta": concept["cta"], "generator": f"{owner} снимает и публикует лично",
                "execution_mode": "human-owner",
                "repurpose_group": f"oct-{campaign_index}" if campaign_index else "owner-commercial",
                "rationale": concept["retention"], "status": "AWAITING_RECORDING", "details": details,
            })
    validate_owner_reels(result)
    return result


def validate_owner_reels(items):
    ids = [item["details"]["reelScriptId"] for item in items]
    hooks = [item["details"]["hook"] for item in items]
    if len(items) != 60 or len(set(ids)) != 60 or len(set(hooks)) != 60:
        raise ValueError("Owner plan must contain 60 distinct scripts and hooks")
    for item in items:
        detail = item["details"]
        if not (10 <= detail["durationSeconds"] <= 55):
            raise ValueError(f"Unexpected duration: {detail['reelScriptId']}")
        if len(detail["talkingPoints"]) != 4 or len(detail["shotList"]) < 2:
            raise ValueError("Script must have a complete story and real shots")
        if detail.get("leadMagnet") and len(detail["leadMagnet"]["content"]) < 4:
            raise ValueError("Do not promise a material without a prepared payload")
