def rubric_sequence():
    """Spread the reviewed mix over the month, with a different rubric in each next slot."""
    counts = {key: 0 for key in RUBRICS}
    sequence = []
    for position in range(60):
        candidates = [key for key in RUBRICS
                      if counts[key] < RUBRICS[key][1] and (not sequence or key != sequence[-1])]
        if not candidates:
            raise ValueError("Cannot distribute rubric mix without adjacent repetitions")
        chosen = max(candidates, key=lambda key: RUBRICS[key][1] * (position + 1) / 60 - counts[key])
        sequence.append(chosen)
        counts[chosen] += 1
    return sequence


def build_owner_reels(owner, campaigns, month):
    if owner == "Алексей":
        topics, prefix = KARP, "karp"
    elif owner == "Вероника":
        topics, prefix = VERONIKA, "veronika"
    else:
        raise ValueError("No reviewed owner briefs for this owner")
    for key, (_, expected, _) in RUBRICS.items():
        if len(topics[key]) != expected:
            raise ValueError(f"{owner}: wrong number of topics for {key}")
    start = datetime.fromisoformat(month + "-01").replace(tzinfo=WARSAW)
