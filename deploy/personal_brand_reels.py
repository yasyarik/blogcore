def validate_owner_reels(items):
    if len(items) != 60 or len({item["details"]["reelScriptId"] for item in items}) != 60:
        raise ValueError("Owner calendar must contain 60 unique existing slots")
    if len({item["title"] for item in items}) != 60:
        raise ValueError("Owner topics must be distinct")
    previous = None
    for item in sorted(items, key=lambda value: value["details"]["publishAt"]):
        detail = item["details"]
        if detail["rubricKey"] == previous:
            raise ValueError("Consecutive Reels must use different rubrics")
        previous = detail["rubricKey"]
        if len(detail["focusPoints"]) != 3 or any(not value for value in detail["focusPoints"]):
            raise ValueError("Every brief needs three concrete editorial directions")
        if any(key in detail for key in ("spokenText", "talkingPoints", "shotList", "hook", "durationSeconds", "scriptRevision")):
            raise ValueError("Live owner briefs must not contain literal or timed scripts")
        if detail.get("leadMagnet") and len(detail["leadMagnet"]["content"]) < 4:
            raise ValueError("Do not promise an unprepared material")
