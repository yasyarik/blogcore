def seed(db_path, replace=False):
    connection = sqlite3.connect(str(db_path), timeout=30)
    connection.row_factory = sqlite3.Row
    now = datetime.now(WARSAW).astimezone().isoformat(timespec="seconds")
    results = []
    try:
        for domain, config in BRANDS.items():
            site = connection.execute("select id from sites where lower(domain)=?", (domain,)).fetchone()
            if not site:
                raise RuntimeError(f"Site not found: {domain}")
            site_id = int(site["id"])
            existing = connection.execute(
                "select count(*) from agent_media_plan_items where site_id=? and json_extract(details_json,'$.planMonth')=?",
                (site_id, PLAN_MONTH),
            ).fetchone()[0]
            if existing and not replace:
                results.append({"domain": domain, "status": "kept", "items": existing})
                continue
            if existing:
                connection.execute(
                    "delete from agent_media_plan_items where site_id=? and json_extract(details_json,'$.planMonth')=?",
                    (site_id, PLAN_MONTH),
                )
            profile = connection.execute("select strategy_version from agent_strategy_profiles where site_id=?", (site_id,)).fetchone()
            version = int(profile["strategy_version"] or 0) if profile else 0
            items = build_items(config)
            for item in items:
                connection.execute(
                    """insert into agent_media_plan_items
                       (site_id,strategy_version,week,channel,format,title,objective,funnel_stage,cta,generator,kpi,execution_mode,repurpose_group,rationale,status,details_json,created_at,updated_at)
                       values(?,?,?,?,?,?,?,?,?,?,?,?,?,?,?,?,?,?)""",
                    (site_id, version, item["week"], item["channel"], item["format"], item["title"], item["objective"], item["funnel_stage"], item["cta"], item["generator"], "Публикация по расписанию; сохранения, ответы и целевые обращения", item["execution_mode"], item["repurpose_group"], item["rationale"], item["status"], json.dumps(item["details"], ensure_ascii=False), now, now),
                )
            results.append({"domain": domain, "status": "seeded", "items": len(items), "manualReels": sum(1 for item in items if item["execution_mode"] == "human-owner")})
        connection.commit()
        return results
    finally:
        connection.close()


def main():
    parser = argparse.ArgumentParser()
    parser.add_argument("--db", default=str(Path(__file__).resolve().parents[1] / "data" / "blog_core.sqlite3"))
    parser.add_argument("--replace", action="store_true")
    args = parser.parse_args()
    print(json.dumps(seed(Path(args.db), replace=args.replace), ensure_ascii=False, indent=2))


if __name__ == "__main__":
    main()
