def growth_brief(owner, title, family):
    strategy = BRAND_STRATEGIES[owner]
    text = title.lower()
    audience = "home"
    if owner == "Вероника":
        if any(word in text for word in ("коммер", "бизнес", "помещени", "доставки")):
            audience = "commercial"
        elif "вилл" in text or "второй дом" in text:
            audience = "villa"
    elif any(word in text for word in ("аренд", "доходност", "ликвид")):
        audience = "investment"
    label, need = strategy["audiences"][audience]
    test_label, hypothesis, primary, secondary = TESTS[family]
    series = strategy["series"].get(family, test_label)
    if audience == "commercial":
        series = "Помещение под задачу бизнеса"
    elif audience == "villa":
        series = "Второй дом без отпускных иллюзий"
    return {
        "revision": REVISION, "audienceKey": audience, "audience": label,
        "audienceNeed": need, "series": series,
        "testFamily": family, "testLabel": test_label, "hypothesis": hypothesis,
        "primarySignal": primary, "secondarySignal": secondary,
        "measurementState": "awaiting_actual_publication_data",
    }


